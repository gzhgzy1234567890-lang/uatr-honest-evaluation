#!/usr/bin/env python3
"""W1-02b — append a TRUE vessel-disjoint protocol to the DeepShip split file.

Why this exists
---------------
The frozen DeepShip split file ships three protocols (clip_random, rec_random,
temporal).  All of them let the same SHIP appear on both sides of the split
(temporal still overlaps 40-60% of vessels), so DeepShip has no honest
identity-disjoint number.  DeepShip's index does carry a vessel identity
(`ship_name`, 242 ships across 609 recordings), so the honest protocol is
constructible -- this script builds it and merges it with the frozen file.

Discipline
----------
- Grouping unit is `ship_name`, exactly the column the runner's leak check uses
  (VESSEL_COL["deepship"]), so split unit and reported leak rate agree.
- One rec_key must map to exactly one (ship_name, class_dir); anything else is
  an error, not a warning -- a recording split across vessels would silently
  fake an honest protocol.
- Split assignment happens at the VESSEL level per class, 70/15/15, with the
  same rounding guards and the same stable_seed("{protocol}|{seed_index}")
  scheme as w1_02, so the file can be regenerated byte-for-byte.
- Classes with fewer than 3 vessels cannot fill three splits: they are assigned
  wholly to train and REPORTED (never silently dropped) -- same policy as the
  runner's group_split for ShipsEar.
- The frozen rows are copied through untouched; the merged file only ever gains
  (protocol, seed) pairs that were not present.

Output
------
--out  (default: <dir of --base>/deepship_splits_vessel.csv.gz)
    one gzipped csv, columns protocol, seed, rec_key, clip_idx, split --
    frozen rows + vessel_disjoint x N seeds.
    Also writes a .report.txt next to it.
"""
from __future__ import annotations

import argparse
import csv
import gzip
import hashlib
import random
from collections import Counter, defaultdict
from pathlib import Path

TRAIN_FRAC, VAL_FRAC = 0.70, 0.15


def stable_seed(protocol: str, seed_index: int) -> int:
    digest = hashlib.sha256(f"{protocol}|{seed_index}".encode()).digest()
    return int.from_bytes(digest[:8], "big")


def main() -> int:
    ap = argparse.ArgumentParser(description="Append DeepShip vessel_disjoint splits.")
    ap.add_argument("--index", required=True,
                    help="deepship/index.csv (needs rec_key, clip_idx, class_dir, ship_name)")
    ap.add_argument("--base", default="",
                    help="existing deepship_splits.csv.gz whose rows are copied through "
                         "(default: none -- output holds only the new protocol)")
    ap.add_argument("--out", default="",
                    help="output .csv.gz path (default: alongside --base, or cwd)")
    ap.add_argument("--n-seeds", type=int, default=10)
    ap.add_argument("--protocol", default="vessel_disjoint")
    ap.add_argument("--exclude-unnamed", action="store_true",
                    help="sensitivity control: DROP the AIS-unjoined recordings instead of "
                         "keeping them as singleton vessels (for the singleton-leakage "
                         "comparison; the paper's main numbers keep them)")
    args = ap.parse_args()

    # ------------------------------------------------------------------ index
    with open(args.index, encoding="utf-8", newline="") as fh:
        rows = list(csv.DictReader(fh))
    if not rows:
        raise SystemExit(f"{args.index} is empty")
    for col in ("rec_key", "clip_idx", "class_dir", "ship_name"):
        if col not in rows[0]:
            raise SystemExit(f"{args.index} has no {col!r} column -- cannot group by vessel")

    rec_meta: dict[str, tuple[str, str]] = {}
    for r in rows:
        meta = (r["ship_name"].strip(), r["class_dir"].strip())
        prev = rec_meta.setdefault(r["rec_key"], meta)
        if prev != meta:
            raise SystemExit(
                f"rec_key {r['rec_key']!r} maps to vessels {prev} and {meta} -- "
                "a recording must belong to exactly one ship; refusing to build "
                "a fake-honest protocol")
    print(f"[index] {len(rows):,} clips, {len(rec_meta):,} recordings")

    rec_clips: dict[str, list[str]] = defaultdict(list)
    for r in rows:
        rec_clips[r["rec_key"]].append(r["clip_idx"])

    unnamed = sorted(k for k, (v, _) in rec_meta.items() if not v)
    if unnamed and args.exclude_unnamed:
        # sensitivity control (--exclude-unnamed): drop the AIS-unjoined
        # recordings entirely instead of keeping them as singletons
        excl_by_class = Counter(rec_meta[k][1] for k in unnamed)
        n_unnamed_clips = sum(len(rec_clips[k]) for k in unnamed)
        for k in unnamed:
            del rec_meta[k]
            del rec_clips[k]
        print(f"[warn ] {len(unnamed)} recordings ({n_unnamed_clips:,} clips) with empty "
              f"ship_name EXCLUDED (sensitivity control); excluded clips by class: "
              f"{dict(sorted(excl_by_class.items()))}")
    elif unnamed:
        # AIS join failed for these recordings (join_method='none' in the
        # metadata).  Dropping them would bias the class mix (Passenger holds
        # most of them), so they stay -- each as its OWN vessel (group =
        # rec_key).  The runner's leak check applies the same rule, so what the
        # split promises and what the leak check verifies stay identical.
        # Residual identity leakage is bounded by the unnamed mass and is
        # reported per seed below.
        for k in unnamed:
            v, c = rec_meta[k]
            rec_meta[k] = (f"singleton::{k}", c)
        n_unnamed_clips = sum(len(rec_clips[k]) for k in unnamed)
        print(f"[warn ] {len(unnamed)} recordings ({n_unnamed_clips:,} clips) have an "
              f"empty ship_name -> treated as singleton vessels, kept in the corpus")
    vessel_of: dict[str, str] = {rec: v for rec, (v, _) in rec_meta.items()}
    vessel_class: dict[str, str] = {}
    for v, c in rec_meta.values():
        vessel_class[v] = c
    if unnamed and not args.exclude_unnamed:
        print(f"[index] {len(vessel_class)} vessels (incl. {len(unnamed)} singletons) "
              f"across {len(rec_meta)} recordings")
    else:
        print(f"[index] {len(vessel_class)} vessels across {len(rec_meta)} recordings")

    # ------------------------------------------------- vessel-level assignment
    by_class: dict[str, list[str]] = defaultdict(list)
    for v, c in vessel_class.items():
        by_class[c].append(v)

    new_rows: list[tuple[str, int, str, str, str]] = []
    summary: list[dict] = []
    dropped_all: list[str] = []

    for seed in range(args.n_seeds):
        rng = random.Random(stable_seed(args.protocol, seed))
        assign: dict[str, str] = {}
        dropped: list[str] = []
        for cls, vs in sorted(by_class.items()):
            vs = sorted(vs)
            rng.shuffle(vs)
            n = len(vs)
            if n < 3:
                dropped.append(f"{cls}:{n}")
                for v in vs:
                    assign[v] = "train"
                continue
            n_train = int(round(n * TRAIN_FRAC))
            n_val = int(round(n * VAL_FRAC))
            if n >= 3 and n - n_train - n_val < 1:
                n_val = max(0, n - n_train - 1)
            for i, v in enumerate(vs):
                assign[v] = "train" if i < n_train else (
                    "val" if i < n_train + n_val else "test")
        dropped_all = dropped  # same every seed; keep the last for the report
        for rec, v in vessel_of.items():
            s = assign[v]
            for k in rec_clips[rec]:
                new_rows.append((args.protocol, seed, rec, k, s))

        # per-seed summary + the two leak checks that must both be zero
        cnt = Counter()
        rec_seen: dict[str, set] = defaultdict(set)
        ves_seen: dict[str, set] = defaultdict(set)
        for p, sd, rec, _, s in new_rows:
            if sd != seed:
                continue
            cnt[s] += 1
            rec_seen[s].add(rec)
            ves_seen[s].add(vessel_of[rec])
        rec_overlap = len(set(rec_seen["train"]) & set(rec_seen["test"]))
        ves_overlap = len(set(ves_seen["train"]) & set(ves_seen["test"]))
        summary.append({"seed": seed, "clips": dict(cnt),
                        "vessels": {s: len(ves_seen[s]) for s in ("train", "val", "test")},
                        "rec_overlap": rec_overlap, "vessel_overlap": ves_overlap})
        if rec_overlap or ves_overlap:
            raise SystemExit(f"seed {seed}: overlap rec={rec_overlap} vessel={ves_overlap} "
                             "-- the honest protocol leaked; refusing to write it")

    # ------------------------------------------------------- merge with frozen
    base_rows: list[dict] = []
    if args.base:
        opener = gzip.open if str(args.base).endswith(".gz") else open
        with opener(args.base, "rt", newline="", encoding="utf-8") as fh:
            base_rows = list(csv.DictReader(fh))
        print(f"[base ] {len(base_rows):,} frozen rows from {args.base}")

    seen_pair = {(r["protocol"], int(r["seed"])) for r in base_rows}
    if args.protocol in {p for p, _ in seen_pair}:
        raise SystemExit(f"frozen file already holds a {args.protocol!r} protocol -- "
                         "refusing to append a second copy (regenerate instead)")

    out = Path(args.out) if args.out else (
        (Path(args.base).parent / "deepship_splits_vessel.csv.gz")
        if args.base else Path("deepship_splits_vessel.csv.gz"))
    out.parent.mkdir(parents=True, exist_ok=True)

    with gzip.open(out, "wt", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["protocol", "seed", "rec_key", "clip_idx", "split"])
        for r in base_rows:
            w.writerow([r["protocol"], r["seed"], r["rec_key"], r["clip_idx"], r["split"]])
        for row in new_rows:
            w.writerow(row)
    n_total = len(base_rows) + len(new_rows)
    print(f"[out  ] {n_total:,} rows -> {out}")

    # ------------------------------------------------------------------ report
    lines = ["=" * 78, "DeepShip vessel_disjoint (w1_02b)", "=" * 78,
             f"index          : {args.index}",
             f"vessels        : {len(vessel_class)} across {len(rec_meta)} recordings",
             f"seeds          : {args.n_seeds}",
             f"dropped (<3 vessels/class): {dropped_all or 'none'}", ""]
    for s in summary:
        lines.append(
            f"  seed {s['seed']}: clips {s['clips']}  vessels {s['vessels']}  "
            f"rec_overlap={s['rec_overlap']} vessel_overlap={s['vessel_overlap']}")
    lines += ["", f"written: {out}", f"next: pass this file to the runner via --split-file"]
    text = "\n".join(lines)
    print()
    print(text)
    Path(str(out).rsplit(".csv.gz", 1)[0] + ".report.txt").write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
